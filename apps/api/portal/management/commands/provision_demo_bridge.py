"""Local synthetic product bridge bootstrap; credentials go only to an ignored file."""
import secrets
from datetime import timedelta
from pathlib import Path

from django.conf import settings
from django.contrib.auth import get_user_model
from django.core.management.base import BaseCommand, CommandError
from django.utils import timezone

from portal.api_key_auth import digest
from portal.models import Tenant, Project, TenantMembership, ProjectMembership, APIKey, AutomationConfig
from portal.security import tenant_context, audit


class Command(BaseCommand):
    help = 'Development-only: create a product support project and customer-bridge credential.'

    def add_arguments(self, parser):
        parser.add_argument('--product', choices=['ototeklif', 'fphr', 'fpfinansman'], required=True)
        parser.add_argument('--tenant', required=True)
        parser.add_argument('--admin', default='admin')
        parser.add_argument('--output', required=True)
        parser.add_argument('--rotate', action='store_true', help='Revoke prior credentials generated by this demo command for this product.')

    def handle(self, *args, **options):
        if not settings.DEBUG:
            raise CommandError('Demo bridge provisioning is development-only.')
        output = Path(options['output']).resolve()
        scratch = settings.BASE_DIR.parent.parent / '.runtime'
        if not output.is_relative_to(scratch.resolve()):
            raise CommandError('Output must be inside the ignored .runtime folder.')
        admin = get_user_model().objects.filter(username=options['admin'], is_active=True).first()
        tenant = Tenant.objects.filter(pk=options['tenant'], active=True).first()
        if not admin or not tenant or not TenantMembership.objects.filter(tenant=tenant, user=admin, role='admin', active=True).exists():
            raise CommandError('Existing demo tenant administrator required.')
        product = options['product']
        with tenant_context(tenant.pk, admin.pk):
            project, _ = Project.objects.get_or_create(tenant=tenant, code=product, defaults={'name': product + ' Destek'})
            ProjectMembership.objects.get_or_create(tenant=tenant, project=project, user=admin, defaults={'role': 'manager'})
            service, created = get_user_model().objects.get_or_create(username=f'demo-bridge-{tenant.pk.hex[:8]}-{product}', defaults={'first_name': product, 'last_name': 'Ürün Köprüsü'})
            if created:
                service.set_unusable_password()
                service.save()
            TenantMembership.objects.get_or_create(tenant=tenant, user=service)
            ProjectMembership.objects.get_or_create(tenant=tenant, project=project, user=service, defaults={'role': 'manager'})
            bots = {user.username: user for user in get_user_model().objects.filter(username__in=['customer-bot', 'solution-bot'], is_active=True)}
            if len(bots) == 2:
                for bot in bots.values():
                    TenantMembership.objects.get_or_create(tenant=tenant, user=bot)
                    ProjectMembership.objects.get_or_create(tenant=tenant, project=project, user=bot, defaults={'role': 'agent'})
                AutomationConfig.objects.get_or_create(tenant=tenant, project=project, defaults={
                    'bot': bots['customer-bot'], 'external_agents': [bots['solution-bot'].pk]})
            prefix = secrets.token_hex(6)
            if options['rotate']:
                APIKey.objects.filter(tenant=tenant, project=project, user=service, name='Local demo product bridge', revoked_at__isnull=True).update(revoked_at=timezone.now())
                audit(admin, tenant, project, 'demo_bridge_rotated', project.pk)
            token = f'fpsk_{prefix}_{secrets.token_urlsafe(32)}'
            APIKey.objects.create(tenant=tenant, project=project, user=service, name='Local demo product bridge',
                                  mode='customer_bridge', prefix=prefix, secret_hash=digest(token), expires_at=timezone.now()+timedelta(days=90))
            output.parent.mkdir(parents=True, exist_ok=True)
            output.write_text(f'FP_SUPPORT_PORTAL_URL=http://127.0.0.1:8080\nFP_SUPPORT_TENANT_ID={tenant.pk}\nFP_SUPPORT_PROJECT_ID={project.pk}\nFP_SUPPORT_API_KEY={token}\n', encoding='utf-8')
            audit(admin, tenant, project, 'demo_bridge_provisioned', project.pk)
        self.stdout.write(f'{product} demo bridge configured. Credential saved to ignored output file; not printed.')
