#!/bin/sh
set -eu
psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" --set=app_password="$APP_DB_PASSWORD" <<'SQL'
CREATE ROLE support_app LOGIN PASSWORD :'app_password' NOSUPERUSER NOBYPASSRLS;
GRANT CONNECT ON DATABASE support TO support_app;
GRANT USAGE ON SCHEMA public TO support_app;
ALTER DEFAULT PRIVILEGES FOR ROLE support_owner IN SCHEMA public GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO support_app;
ALTER DEFAULT PRIVILEGES FOR ROLE support_owner IN SCHEMA public GRANT USAGE, SELECT ON SEQUENCES TO support_app;
SQL
